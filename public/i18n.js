  var KEY = "malariascope.lang";
  var lang = "en";
  try {
    lang = localStorage.getItem(KEY) || ((navigator.language || "").slice(0, 2) === "fr" ? "fr" : "en");
  } catch (e) { /* storage blocked: keep English */ }
  if (!STRINGS[lang]) lang = "en";

  function t(key, vars) {
    var s = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
    if (vars) {
      Object.keys(vars).forEach(function (k) { s = s.split("{" + k + "}").join(String(vars[k])); });
    }
    return s;
  }

  function apply(doc) {
    doc.documentElement.lang = lang;
    doc.querySelectorAll("[data-i18n]").forEach(function (e) { e.textContent = t(e.dataset.i18n); });
    doc.querySelectorAll("[data-i18n-placeholder]").forEach(function (e) { e.placeholder = t(e.dataset.i18nPlaceholder); });
    doc.querySelectorAll("[data-i18n-aria]").forEach(function (e) { e.setAttribute("aria-label", t(e.dataset.i18nAria)); });
  }

  function setLang(next) {
    lang = STRINGS[next] ? next : "en";
    try { localStorage.setItem(KEY, lang); } catch (e) { /* ignore */ }
  }

  function number(n) { return Number(n).toLocaleString(lang === "fr" ? "fr-FR" : "en-US"); }
  function locale() { return lang === "fr" ? "fr-FR" : "en-GB"; }

  root.I18n = { t: t, apply: apply, setLang: setLang, get lang() { return lang; }, number: number, locale: locale };
